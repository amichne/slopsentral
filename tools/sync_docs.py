"""Project the canonical Pi guide into the public Mintlify site."""

from __future__ import annotations

import argparse
import hashlib
import json
import posixpath
import re
from dataclasses import dataclass
from enum import StrEnum
from pathlib import Path
from typing import assert_never
from urllib.parse import urlsplit

SOURCE = Path("docs/pi-harness.md")
TARGET = Path("docs/public/guides/pi.mdx")
HEADER = """---
title: "Use Slopsentral in Pi"
description: "Install the package, select capabilities, and inspect hook policies and release evidence."
icon: "terminal"
---
"""
LINK = re.compile(r"(\[[^\]\n]+\]\()([^\s)]+)(\))")
FENCE = re.compile(r"^\s*(`{3,}|~{3,})")


def public_link(match: re.Match[str]) -> str:
    target = match[2]
    if urlsplit(target).scheme or target.startswith("#"):
        return match[0]
    path = posixpath.normpath(f"docs/{target}")
    return f"{match[1]}https://github.com/amichne/slopsentral/blob/main/{path}{match[3]}"


def public_body(source: str) -> str:
    lines: list[str] = []
    fence = ""
    for line in source.splitlines(keepends=True):
        marker = FENCE.match(line)
        if marker:
            delimiter = marker[1]
            if not fence:
                fence = delimiter
            elif delimiter[0] == fence[0] and len(delimiter) >= len(fence):
                fence = ""
            lines.append(line)
        else:
            lines.append(line if fence else LINK.sub(public_link, line))
    return "".join(lines)


class Failure(StrEnum):
    INVALID_SOURCE = "INVALID_SOURCE"
    READ_FAILED = "READ_FAILED"
    WRITE_FAILED = "WRITE_FAILED"
    STALE = "STALE"


class Status(StrEnum):
    CURRENT = "CURRENT"
    GENERATED = "GENERATED"


@dataclass(frozen=True, slots=True)
class Rendered:
    content: str


@dataclass(frozen=True, slots=True)
class Rejected:
    reason: Failure


def render(source: str) -> Rendered | Rejected:
    if not source.startswith("# Pi harness\n\n"):
        return Rejected(Failure.INVALID_SOURCE)
    body = public_body(source.removeprefix("# Pi harness\n\n"))
    digest = hashlib.sha256(source.encode()).hexdigest()
    return Rendered(
        f"{HEADER}\n{{/* Generated by tools/sync_docs.py from docs/pi-harness.md. "
        f"SHA-256: {digest}. Do not edit this page. */}}\n\n{body}"
    )


def reject(reason: Failure) -> int:
    print(json.dumps({"type": "REJECTED", "reason": reason.value}))
    return 1


def examine(target: Path, page: Rendered) -> Status | Failure:
    try:
        current = target.read_text(encoding="utf-8")
    except FileNotFoundError:
        return Failure.STALE
    except (OSError, UnicodeError):
        return Failure.READ_FAILED
    return Status.CURRENT if current == page.content else Failure.STALE


def write(target: Path, page: Rendered) -> Status | Failure:
    try:
        target.parent.mkdir(parents=True, exist_ok=True)
        _ = target.write_text(page.content, encoding="utf-8")
    except OSError:
        return Failure.WRITE_FAILED
    return Status.GENERATED


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    _ = parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    _ = parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(args.root)
    try:
        source = (root / SOURCE).read_text(encoding="utf-8")
    except (OSError, UnicodeError):
        return reject(Failure.READ_FAILED)
    result = render(source)
    match result:
        case Rejected(reason):
            return reject(reason)
        case Rendered():
            outcome = examine(root / TARGET, result) if args.check else write(root / TARGET, result)
            if isinstance(outcome, Failure):
                return reject(outcome)
            print(json.dumps({"type": outcome.value, "target": TARGET.as_posix()}))
            return 0
    assert_never(result)


if __name__ == "__main__":
    raise SystemExit(main())
