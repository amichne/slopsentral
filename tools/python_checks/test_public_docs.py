@pytest.mark.parametrize("change", ["query", "fragment", "external"])
def test_live_preserves_query_fragment_and_external_target(tmp_path: Path, change: str) -> None:
    root = tmp_path / "project"
    fixture(root)
    source = (
        "# Fixture\n\nRead the [guide](docs/guide.md?mode=read#details).\n\n"
        "Read the [reference](https://authority.example/item?version=2#contract).\n"
    )
    write(root, "README.md", source)
    synced_result = cli(root, "sync")
    assert synced_result.returncode == 0, synced_result.stdout + synced_result.stderr
    remote = source.replace(
        "docs/guide.md?mode=read#details", "{{ORIGIN}}/guide.md?mode=read#details"
    )
    responses = live_responses()
    responses["/index.md"] = (HTTPStatus.OK, "text/markdown", remote)
    with site_server(responses) as (url, _requests):
        accepted = cli(root, "live", "--base-url", url, "--timeout", "0")
    assert accepted.returncode == 0, accepted.stdout + accepted.stderr
    replacements = {
        "query": ("mode=read", "mode=delete"),
        "fragment": ("#details", "#wrong"),
        "external": ("authority.example/item", "obsolete.invalid/removed"),
    }
    before, after = replacements[change]
    responses["/index.md"] = (HTTPStatus.OK, "text/markdown", remote.replace(before, after))
    with site_server(responses) as (url, _requests):
        rejected = cli(root, "live", "--base-url", url, "--timeout", "0")
    assert rejected.returncode == 1, rejected.stdout + rejected.stderr
    assert report(rejected)["type"] == "STALE"
