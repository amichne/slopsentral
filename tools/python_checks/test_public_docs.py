SCRIPT = Path(__file__).resolve().parents[1] / "public_docs.py"
HOME = "# Fixture\n\nRead the [guide](docs/guide.md#details).\n"
GUIDE = "# Guide\n\n## Details\n\nKeep the current source claim.\n\n```sh\nprintf 'literal <value>'\n```\n"


def write(root: Path, name: str, content: str) -> None:
    target = root / name
    target.parent.mkdir(parents=True, exist_ok=True)
    _ = target.write_text(content, encoding="utf-8")


def fixture(root: Path, change: str = "") -> None:
    root.mkdir(parents=True)
    write(root, "README.md", HOME)
    write(root, "docs/guide.md", GUIDE)
    pages: list[dict[str, str]] = [
        {"source": "README.md", "route": "index", "description": "Read the project."},
        {"source": "docs/guide.md", "route": "guide", "description": "Use the guide."},
    ]
    routes = ["index", "guide"]
    redirects = [{"source": "/old", "destination": "/guide"}]
    page_changes = {
        "duplicate-route": ("route", "index"),
        "duplicate-source": ("source", "README.md"),
        "route-traversal": ("route", "../outside"),
        "source-output": ("source", "docs/public/guide.mdx"),
    }
    if change in page_changes:
        field, value = page_changes[change]
        pages[1][field] = value
    route_changes = {
        "nav-missing": ["index"],
        "nav-duplicate": ["index", "guide", "guide"],
        "nav-unmapped": ["index", "guide", "absent"],
    }
    if change in route_changes:
        routes = route_changes[change]
    if change == "redirect-missing":
        redirects[0]["destination"] = "/absent"
    mutate_source(root, change)
    write(
        root,
        "docs/site.json",
        json.dumps(
            {
                "schemaVersion": 1,
                "site": {
                    "name": "Fixture",
                    "theme": "mint",
                    "colors": {"primary": "#059669"},
                    "navigation": {"groups": [{"group": "Start", "pages": routes}]},
                    "redirects": redirects,
                },
                "pages": pages,
            }
        ),
    )


def mutate_source(root: Path, change: str) -> None:
    replacements = {
        "source-output": ("docs/public/guide.mdx", GUIDE),
        "empty-source": ("docs/guide.md", ""),
        "missing-link": ("README.md", "# Fixture\n\nRead the [absent](docs/absent.md).\n"),
        "missing-anchor": ("README.md", "# Fixture\n\nRead the [guide](docs/guide.md#absent).\n"),
    }
    if change in replacements:
        name, text = replacements[change]
        write(root, name, text)
    if change == "missing-source":
        (root / "docs/guide.md").unlink()


def cli(root: Path, command: str, *arguments: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, str(SCRIPT), command, "--repo", str(root), *arguments],
        cwd=root.parent,
        capture_output=True,
        text=True,
        check=False,
        timeout=30,
    )


def report(result: subprocess.CompletedProcess[str]) -> dict[str, object]:
    value: dict[str, object] = json.loads(result.stdout)
    return value


def synced(root: Path) -> None:
    fixture(root)
    result = cli(root, "sync")
    assert result.returncode == 0, result.stdout + result.stderr
    assert report(result)["type"] == "SYNCED"


def test_sync_and_check_preserve_code_and_rewrite_links(tmp_path: Path) -> None:
    root = tmp_path / "project ; literal"
    fixture(root)
    write(root, "source/service.py", "def run(): return 1\n")
    write(
        root,
        "README.md",
        HOME + "\nRead the [source](source/service.py#L1).\n\n```md\n[Code](missing.md)\n```\n",
    )
    result = cli(root, "sync")
    assert result.returncode == 0, result.stdout + result.stderr
    assert report(result)["type"] == "SYNCED"
    output = (root / "docs/public/index.mdx").read_text(encoding="utf-8")
    assert "[guide](/guide#details)" in output
    assert "{/* Generated by slopsentral-site." in output
    assert "<!--" not in output
    assert "https://github.com/amichne/slopsentral/blob/main/source/service.py#L1" in output
    assert "```md\n[Code](missing.md)\n```" in output
    assert "printf 'literal <value>'" in (root / "docs/public/guide.mdx").read_text(
        encoding="utf-8"
    )
    checked = cli(root, "check")
    assert checked.returncode == 0, checked.stdout + checked.stderr
    assert report(checked)["type"] == "CURRENT"


