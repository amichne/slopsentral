@pytest.mark.parametrize(
    "change",
    ["missing-tree", "missing-config", "missing-page", "edited-page", "extra-page", "source-drift"],
)
def test_missing_or_stale_output_fails_without_changes(tmp_path: Path, change: str) -> None:
    root = tmp_path / "project"
    synced(root)
    match change:
        case "missing-tree":
            for path in (root / "docs/public").rglob("*"):
                if path.is_file():
                    path.unlink()
        case "missing-config":
            (root / "docs/public/docs.json").unlink()
        case "missing-page":
            (root / "docs/public/guide.mdx").unlink()
        case "edited-page":
            write(root, "docs/public/guide.mdx", "# Guide\n\nUnreviewed copy.\n")
        case "extra-page":
            write(root, "docs/public/extra.mdx", "# Unregistered\n")
        case "source-drift":
            write(
                root, "docs/guide.md", GUIDE.replace("current source claim", "changed source claim")
            )
        case _:
            raise AssertionError(change)
    before = {path: path.read_bytes() for path in root.rglob("*") if path.is_file()}
    result = cli(root, "check")
    assert result.returncode == 1, result.stdout + result.stderr
    assert report(result)["type"] == "STALE"
    assert {path: path.read_bytes() for path in root.rglob("*") if path.is_file()} == before


@contextmanager
def site_server(
    responses: dict[str, tuple[int, str, str]],
) -> Iterator[tuple[str, list[str]]]:
    requests: list[str] = []

    class Handler(BaseHTTPRequestHandler):
        def do_GET(self) -> None:
            path = urlsplit(self.path).path
            requests.append(path)
            status, content_type, body = responses.get(
                path, (HTTPStatus.NOT_FOUND, "text/plain", "Missing page")
            )
            self.send_response(status)
            self.send_header("Content-Type", content_type)
            self.end_headers()
            _ = self.wfile.write(
                body.replace("{{ORIGIN}}", f"http://127.0.0.1:{server.server_port}").encode("utf-8")
            )

    with ThreadingHTTPServer(("127.0.0.1", 0), Handler) as server:
        worker = Thread(target=server.serve_forever, daemon=True)
        worker.start()
        try:
            yield f"http://127.0.0.1:{server.server_port}", requests
        finally:
            server.shutdown()
            worker.join()


def live_responses() -> dict[str, tuple[int, str, str]]:
    return {
        "/index.md": (
            HTTPStatus.OK,
            "text/markdown; charset=utf-8",
            "> ## Documentation Index\n\n# Fixture\n\nRead the [guide]({{ORIGIN}}/guide.md#details).\n",
        ),
        "/guide.md": (
            HTTPStatus.OK,
            "text/markdown; charset=utf-8",
            GUIDE.replace("```sh", "```sh theme={null}"),
        ),
    }


def test_live_reads_all_routes_and_matches_rendered_markdown(tmp_path: Path) -> None:
    root = tmp_path / "project"
    synced(root)
    with site_server(live_responses()) as (url, requests):
        result = cli(root, "live", "--base-url", url, "--timeout", "0")
    assert result.returncode == 0, result.stdout + result.stderr
    assert report(result)["type"] == "LIVE"
    assert set(requests) == {"/index.md", "/guide.md"}


@pytest.mark.parametrize("change", ["stale-body", "appended-stale", "html-login", "missing-page"])
def test_live_rejects_stale_body_login_and_missing_page(tmp_path: Path, change: str) -> None:
    root = tmp_path / "project"
    synced(root)
    responses = live_responses()
    match change:
        case "stale-body":
            responses["/guide.md"] = (
                HTTPStatus.OK,
                "text/markdown",
                "# Guide\n\n## Details\n\nKeep the old source claim.\n",
            )
        case "appended-stale":
            responses["/guide.md"] = (
                HTTPStatus.OK,
                "text/markdown",
                GUIDE + "\nOld contradictory instructions.\n",
            )
        case "html-login":
            responses["/guide.md"] = (
                HTTPStatus.OK,
                "text/html",
                "<html><body>Sign in to continue</body></html>",
            )
        case "missing-page":
            del responses["/guide.md"]
        case _:
            raise AssertionError(change)
    with site_server(responses) as (url, _requests):
        result = cli(root, "live", "--base-url", url, "--timeout", "0")
    assert result.returncode != 0, result.stdout + result.stderr
    assert report(result)["type"] != "LIVE"


