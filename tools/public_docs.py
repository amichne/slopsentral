def mapping(value: object) -> TypeGuard[Mapping[str, object]]:
    # JSON object keys are strings. All callers receive JSON-decoded values.
    return isinstance(value, Mapping)


def sequence(value: object) -> TypeGuard[list[object]]:
    return isinstance(value, list)


def read(path: Path) -> str | Rejected:
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeError):
        return Rejected(Code.SOURCE, str(path))


def repository_path(name: str) -> bool:
    path = PurePosixPath(name)
    return (
        bool(name)
        and not path.is_absolute()
        and str(path) == name
        and ".." not in path.parts
        and "\\" not in name
    )


def navigation(value: object) -> tuple[str, ...] | Rejected:
    if not mapping(value):
        return Rejected(Code.INPUT, "site.navigation must be an object")
    result: list[str] = []
    for key, child in value.items():
        if key == "pages":
            if not sequence(child) or not all(isinstance(item, str) for item in child):
                return Rejected(Code.INPUT, "navigation pages must be route lists")
            result.extend(item for item in child if isinstance(item, str))
        elif sequence(child):
            for item in child:
                found = navigation(item)
                if isinstance(found, Rejected):
                    return found
                result.extend(found)
    return tuple(result)


def source_spec(value: object) -> _Source | Rejected:
    if not mapping(value) or set(value) != {"source", "route", "description"}:
        return Rejected(Code.INPUT, "each page needs source, route, and description")
    source, route, description = value["source"], value["route"], value["description"]
    if (
        not isinstance(source, str)
        or not repository_path(source)
        or not source.endswith(".md")
        or source.startswith(f"{PUBLIC}/")
    ):
        return Rejected(Code.INPUT, "page source must name canonical repository Markdown")
    if not isinstance(route, str) or re.fullmatch(r"[a-z0-9]+(?:[/-][a-z0-9]+)*", route) is None:
        return Rejected(Code.INPUT, "page route must be a relative kebab-case path")
    if not isinstance(description, str) or not description.strip() or "\n" in description:
        return Rejected(Code.INPUT, "page description must be nonempty text")
    return _Source(source, route, description)


def source_content(content: str, spec: _Source) -> _Page | Rejected:
    if content.startswith("---\n"):
        frontmatter, separator, content = content[4:].partition("\n---\n")
        if not separator or not frontmatter:
            return Rejected(Code.SOURCE, f"unclosed frontmatter: {spec.path}")
    content = content.strip()
    lines = content.splitlines()
    if not lines or not lines[0].startswith("# ") or not "\n".join(lines[1:]).strip():
        return Rejected(Code.SOURCE, f"page needs a title and body: {spec.path}")
    return _Page(spec.path, spec.route, spec.description, lines[0][2:].strip(), content)


def source_page(root: Path, value: object) -> _Page | Rejected:
    spec = source_spec(value)
    if isinstance(spec, Rejected):
        return spec
    path = root / spec.path
    if not path.resolve().is_relative_to(root.resolve()):
        return Rejected(Code.SOURCE, spec.path)
    content = read(path)
    return content if isinstance(content, Rejected) else source_content(content, spec)


def admit_pages(root: Path, entries: object) -> tuple[_Page, ...] | Rejected:
    if not sequence(entries) or not entries:
        return Rejected(Code.INPUT, "nonempty pages are necessary")
    pages: list[_Page] = []
    sources: set[str] = set()
    routes: set[str] = set()
    for entry in entries:
        page = source_page(root, entry)
        if isinstance(page, Rejected):
            return page
        if page.source in sources or page.route in routes:
            return Rejected(Code.INPUT, "duplicate page source or route")
        sources.add(page.source)
        routes.add(page.route)
        pages.append(page)
    return tuple(pages)


def anchors(body: str) -> frozenset[str]:
    counts: Counter[str] = Counter()
    result: set[str] = set()
    tokens = MarkdownIt().parse(body)
    for index, token in enumerate(tokens):
        if token.type != "heading_open":
            continue
        text = inline_text(tokens[index + 1].children or [])
        slug = re.sub(r"[^\w\- ]", "", text.lower()).replace(" ", "-")
        suffix = f"-{counts[slug]}" if counts[slug] else ""
        result.add(slug + suffix)
        counts[slug] += 1
    return frozenset(result)


def redirect_source(value: object, routes: Mapping[str, _Page]) -> str | Rejected:
    if not mapping(value) or set(value) != {"source", "destination"}:
        return Rejected(Code.INPUT, "redirect needs source and destination")
    source, target = value["source"], value["destination"]
    if (
        not isinstance(source, str)
        or not isinstance(target, str)
        or not source.startswith("/")
        or not target.startswith("/")
    ):
        return Rejected(Code.INPUT, "redirect must use site paths")
    old, new = urlsplit(source), urlsplit(target)
    page = routes.get(new.path.removeprefix("/"))
    if (
        not repository_path(old.path.removeprefix("/"))
        or old.query
        or old.fragment
        or old.netloc
        or new.netloc
        or source.removeprefix("/") in routes
        or page is None
        or (new.fragment and new.fragment not in anchors(page.body))
    ):
        return Rejected(Code.INPUT, f"invalid redirect: {source}")
    return source


def admit_site(site: Mapping[str, object], pages: tuple[_Page, ...]) -> Rejected | None:
    routes = {page.route: page for page in pages}
    nav = navigation(site.get("navigation"))
    if isinstance(nav, Rejected):
        return nav
    if Counter(nav) != Counter(routes.keys()):
        return Rejected(Code.INPUT, "navigation must name every route exactly once")
    redirects = site.get("redirects", [])
    if not sequence(redirects):
        return Rejected(Code.INPUT, "redirects must be a list")
    old_routes: set[str] = set()
    for redirect in redirects:
        source = redirect_source(redirect, routes)
        if isinstance(source, Rejected):
            return source
        if source in old_routes:
            return Rejected(Code.INPUT, f"duplicate redirect: {source}")
        old_routes.add(source)
    return None


def manifest(root: Path) -> _Manifest | Rejected:
    raw = read(root / "docs/site.json")
    if isinstance(raw, Rejected):
        return raw
    try:
        value: object = json.loads(raw)
    except json.JSONDecodeError:
        return Rejected(Code.INPUT, "docs/site.json must be JSON")
    if (
        not mapping(value)
        or set(value) != {"schemaVersion", "site", "pages"}
        or value["schemaVersion"] != 1
        or not mapping(value["site"])
    ):
        return Rejected(Code.INPUT, "unknown site manifest shape")
    pages = admit_pages(root, value["pages"])
    if isinstance(pages, Rejected):
        return pages
    failure = admit_site(value["site"], pages)
    return failure if failure is not None else _Manifest(value["site"], pages)


def destination(root: Path, page: _Page, href: str, pages: Mapping[str, _Page]) -> str | Rejected:
    url = urlsplit(href)
    if url.scheme or url.netloc:
        return href
    name = (
        posixpath.normpath(posixpath.join(posixpath.dirname(page.source), unquote(url.path)))
        if url.path
        else page.source
    )
    path = root / name
    if path.is_dir() and (path / "index.md").is_file():
        name = f"{name}/index.md"
        path = root / name
    if (
        not repository_path(name)
        or not path.resolve().is_relative_to(root.resolve())
        or not path.exists()
    ):
        return Rejected(Code.LINK, f"{page.source}: {href}")
    mapped = pages.get(name)
    if mapped is not None and url.fragment and unquote(url.fragment) not in anchors(mapped.body):
        return Rejected(Code.LINK, f"missing anchor: {page.source}: {href}")
    suffix = (f"?{url.query}" if url.query else "") + (f"#{url.fragment}" if url.fragment else "")
    return (f"/{mapped.route}" if mapped is not None else GITHUB + quote(name, safe="/")) + suffix


def parsed_links(tokens: list[Token]) -> tuple[str, ...]:
    result: list[str] = []
    for token in tokens:
        attribute = "src" if token.type == "image" else "href"
        href = token.attrGet(attribute)
        if isinstance(href, str):
            result.append(href)
        if token.children is not None:
            result.extend(parsed_links(token.children))
    return tuple(result)


def link_replacements(
    root: Path, page: _Page, pages: Mapping[str, _Page], tokens: list[Token]
) -> dict[str, str] | Rejected:
    replacements: dict[str, str] = {}
    for href in parsed_links(tokens):
        target = destination(root, page, href, pages)
        if isinstance(target, Rejected):
            return target
        replacements[href] = target
    return replacements


def code_spans(body: str) -> tuple[tuple[int, int], ...]:
    spans: list[tuple[int, int]] = []
    runs = tuple(re.finditer(r"`+", body))
    index = 0
    while index < len(runs):
        opening = runs[index]
        closing = next(
            (number for number in range(index + 1, len(runs)) if runs[number][0] == opening[0]),
            None,
        )
        if closing is None:
            index += 1
        else:
            spans.append((opening.start(), runs[closing].end()))
            index = closing + 1
    return tuple(spans)


def replace_destinations(text: str, replacements: Mapping[str, str]) -> str:
    changes: list[tuple[int, int, str]] = []
    protected = code_spans(text)
    parser = MarkdownIt()
    for match in re.finditer(r"\]\(\s*|^\s*\[[^\]]+\]:\s*", text, re.MULTILINE):
        if any(start <= match.start() < end for start, end in protected):
            continue
        parsed = parseLinkDestination(text, match.end(), len(text))
        if not parsed.ok:
            continue
        target = replacements.get(parser.normalizeLink(parsed.str))
        if target is not None:
            changes.append((match.end(), parsed.pos, target))
    for start, end, target in reversed(changes):
        text = text[:start] + target + text[end:]
    return text


def escape_mdx(text: str) -> str:
    spans = code_spans(text)
    result: list[str] = []
    position = 0
    for start, end in spans:
        result.append(text[position:start].replace("{", "&#123;").replace("}", "&#125;"))
        result.append(text[start:end])
        position = end
    result.append(text[position:].replace("{", "&#123;").replace("}", "&#125;"))
    return "".join(result)


def rewrite(root: Path, page: _Page, pages: Mapping[str, _Page]) -> str | Rejected:
    tokens = MarkdownIt().parse(page.body)
    replacements = link_replacements(root, page, pages, tokens)
    if isinstance(replacements, Rejected):
        return replacements
    lines = page.body.splitlines(keepends=True)
    code_lines: set[int] = set()
    for token in tokens:
        if token.type in {"fence", "code_block"} and token.map is not None:
            code_lines.update(range(*token.map))
    # Process contiguous non-code regions together to preserve multiline code spans.
    result: list[str] = []
    prose: list[str] = []
    for index, line in enumerate(lines):
        if index in code_lines:
            result.append(escape_mdx(replace_destinations("".join(prose), replacements)))
            prose = []
            result.append(line)
        else:
            prose.append(line)
    result.append(escape_mdx(replace_destinations("".join(prose), replacements)))
    return "".join(result)


def project_page(page: _Page, body: str) -> tuple[str, _Page]:
    header = (
        "---\ntitle: "
        + json.dumps(page.title)
        + "\ndescription: "
        + json.dumps(page.description)
        + "\n---\n\n"
    )
    # Mintlify renders the title from frontmatter, so omit its duplicate H1.
    body = body.split("\n", 1)[1].lstrip()
    content = header + MARKER + "\n\n" + body + "\n"
    return content, _Page(page.source, page.route, page.description, page.title, body)


def local_assets(site: Mapping[str, object]) -> tuple[str, ...] | Rejected:
    values: list[object] = []
    logo = site.get("logo")
    if mapping(logo):
        values.extend(logo[key] for key in ("light", "dark") if key in logo)
    elif logo is not None:
        values.append(logo)
    if "favicon" in site:
        values.append(site["favicon"])
    paths: list[str] = []
    for value in values:
        if not isinstance(value, str):
            return Rejected(Code.INPUT, "site assets must be paths or URLs")
        if urlsplit(value).scheme:
            continue
        if not value.startswith("/") or not repository_path(value.removeprefix("/")):
            return Rejected(Code.INPUT, f"invalid local site asset: {value}")
        paths.append(value.removeprefix("/"))
    return tuple(paths)


def prepare(root: Path) -> _Projection | Rejected:
    spec = manifest(root)
    if isinstance(spec, Rejected):
        return spec
    assets = local_assets(spec.site)
    if isinstance(assets, Rejected):
        return assets
    pages = {page.source: page for page in spec.pages}
    files = [("docs.json", json.dumps(dict(spec.site), indent=2, ensure_ascii=False) + "\n")]
    projected: list[_Page] = []
    for page in spec.pages:
        body = rewrite(root, page, pages)
        if isinstance(body, Rejected):
            return body
        content, rendered = project_page(page, body)
        files.append((f"{page.route}.mdx", content))
        projected.append(rendered)
    return _Projection(tuple(files), tuple(projected), assets)


def examine(root: Path, projection: _Projection) -> tuple[str, ...]:
    output = root / PUBLIC
    expected = {name for name, _ in projection.files}
    stale = [name for name, content in projection.files if read(output / name) != content]
    if output.is_dir():
        stale.extend(
            path.relative_to(output).as_posix()
            for path in output.rglob("*")
            if path.suffix in {".md", ".mdx"}
            and path.relative_to(output).as_posix() not in expected
        )
    return tuple(sorted(set(stale)))


def admit_output(root: Path, projection: _Projection) -> _Output | Rejected:
    base = root.resolve()
    output = root / PUBLIC
    files: list[tuple[Path, str]] = []
    targets = (*projection.files, *((name, "") for name in projection.assets))
    for name, content in targets:
        path = output / name
        if not path.resolve().is_relative_to(base):
            return Rejected(Code.OUTPUT, f"output escapes repository: {name}")
        current = path
        while current != base:
            if current.is_symlink():
                return Rejected(Code.OUTPUT, f"output uses a symlink: {name}")
            current = current.parent
        if name in projection.assets:
            if not path.is_file():
                return Rejected(Code.OUTPUT, f"missing public asset: {name}")
        else:
            files.append((path, content))
    return _Output(tuple(files))


def synchronize(output: _Output) -> Rejected | None:
    try:
        for path, content in output.files:
            path.parent.mkdir(parents=True, exist_ok=True)
            _ = path.write_text(content, encoding="utf-8", newline="\n")
    except OSError:
        return Rejected(Code.OUTPUT, "cannot write public projection")
    return None


def inline_text(tokens: list[Token]) -> str:
    result: list[str] = []
    for token in tokens:
        if token.children is not None:
            result.append(inline_text(token.children))
        elif token.type in {"text", "code_inline", "fence", "code_block"}:
            result.append(token.content)
        elif token.type in {"softbreak", "hardbreak"}:
            result.append(" ")
    return "".join(result)


