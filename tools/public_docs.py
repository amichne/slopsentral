def comparable_href(href: str, origin: _Origin) -> str:
    url = urlsplit(href)
    base = urlsplit(origin.value)
    same_origin = url.scheme == base.scheme and url.netloc == origin.authority
    local_path = not url.scheme and not url.netloc and url.path.startswith("/")
    if same_origin or local_path:
        # Mintlify's Markdown endpoint expands local routes into absolute .md
        # links. Queries, fragments, and external destinations stay exact.
        path = (
            "/index"
            if url.path in {"", "/", "/index", "/index.md"}
            else url.path.removesuffix(".md")
        )
        return urlunsplit(("", "", path, url.query, url.fragment))
    return href


def inline_atom(token: Token, origin: _Origin) -> str | _Inline | None:
    match token.type:
        case "text" | "softbreak" | "hardbreak":
            return token.content if token.type == "text" else " "
        case "code_inline":
            return _InlineCode(token.content)
        case "link_open":
            href = token.attrGet("href")
            if isinstance(href, str):
                return _LinkStart(comparable_href(href, origin))
        case "link_close":
            return _LinkEnd()
        case "image":
            src = token.attrGet("src")
            if isinstance(src, str):
                return _Image(comparable_href(src, origin), token.content)
        case _:
            # Emphasis and strong delimiters change style, not content.
            pass
    return None


def prose_parts(tokens: list[Token], origin: _Origin) -> tuple[_Inline, ...]:
    parts: list[_Inline] = []
    pending = ""
    for token in tokens:
        atom = inline_atom(token, origin)
        if isinstance(atom, str):
            pending += atom
        elif atom is not None:
            if pending.strip():
                parts.append(_Text(" ".join(pending.split())))
            pending = ""
            parts.append(atom)
    if pending.strip():
        parts.append(_Text(" ".join(pending.split())))
    return tuple(parts)


def blocks(body: str, origin: _Origin) -> tuple[_Block, ...]:
    result: list[_Block] = []
    for token in MarkdownIt().enable("table").parse(body):
        if token.type == "inline":
            parts = prose_parts(token.children or [], origin)
            if parts:
                result.append(_Prose(parts))
        elif token.type in {"fence", "code_block"}:
            language = token.info.split(maxsplit=1)[0] if token.info else ""
            if language.startswith("theme="):
                language = ""
            result.append(_CodeBlock(language, token.content))
        elif token.type in _TABLE_PARTS:
            style = token.attrGet("style")
            result.append(
                _TableMark(_TABLE_PARTS[token.type], style if isinstance(style, str) else "")
            )
    return tuple(result)


def visible_markup(tokens: list[Token]) -> bool:
    for token in tokens:
        if token.type in {"html_block", "html_inline"}:
            content = token.content.strip()
            if not (content.startswith("<!--") and content.endswith("-->")):
                return True
        if token.children is not None and visible_markup(token.children):
            return True
    return False


def content_matches(page: _Page, remote: str, origin: _Origin) -> bool:
    if visible_markup(MarkdownIt().parse(remote)):
        return False
    received = blocks(remote, origin)
    title = blocks(page.title, origin)
    if len(title) != 1 or title[0] not in received:
        return False
    received = received[received.index(title[0]) + 1 :]
    description = blocks(page.description, origin)
    if received[: len(description)] == description:
        received = received[len(description) :]
    attribution = blocks(PLATFORM_ATTRIBUTION, origin)
    if received[-len(attribution) :] == attribution:
        received = received[: -len(attribution)]
    return received == blocks(page.body, origin)


def admit_origin(origin: str) -> _Origin | Rejected:
    url = urlsplit(origin)
    if (
        url.path not in {"", "/"}
        or url.query
        or url.fragment
        or url.username
        or url.password
        or not url.hostname
        or not (
            url.scheme == "https"
            or (url.scheme == "http" and url.hostname in {"127.0.0.1", "localhost", "::1"})
        )
    ):
        return Rejected(Code.INPUT, "base URL must be an HTTPS origin or loopback fixture")
    return _Origin(origin.rstrip("/"), url.netloc)


def response_failure(
    origin: _Origin, content_type: str, response_url: object, size: int
) -> Rejected | None:
    if not isinstance(response_url, str) or urlsplit(response_url).netloc != origin.authority:
        return Rejected(Code.FETCH, "cross-origin-response")
    if content_type not in {"text/markdown", "text/plain"}:
        bounded = (
            content_type
            if re.fullmatch(r"[a-zA-Z0-9.+-]{1,32}/[a-zA-Z0-9.+-]{1,48}", content_type)
            else "unrecognized"
        )
        return Rejected(Code.FETCH, f"content-type:{bounded}")
    if size > MAX_RESPONSE_BYTES:
        return Rejected(Code.FETCH, f"response-size-limit:{MAX_RESPONSE_BYTES}")
    return None


def fetch(origin: _Origin, page: _Page, timeout: float) -> str | Rejected:
    url = f"{origin.value}/{page.route}.md"
    request = urllib.request.Request(  # noqa: S310 -- URL consists only of an admitted origin and canonical page route
        url, headers={"User-Agent": "slopsentral-site/1", "Cache-Control": "no-cache"}
    )
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:  # noqa: S310 -- admitted HTTPS origin or explicit loopback fixture
            mime = response.headers.get("Content-Type", "").split(";", 1)[0]
            data = response.read(MAX_RESPONSE_BYTES + 1)
            response_url: object = response.url
            failure = response_failure(origin, mime, response_url, len(data))
            return failure if failure is not None else data.decode("utf-8")
    except urllib.error.HTTPError as error:
        return Rejected(Code.FETCH, f"http-status:{error.code}")
    except urllib.error.URLError as error:
        return Rejected(Code.FETCH, f"transport:{type(error.reason).__name__[:64]}")
    except UnicodeError as error:
        return Rejected(Code.FETCH, f"decode:{type(error).__name__[:64]}")
    except (TimeoutError, OSError) as error:
        return Rejected(Code.FETCH, f"transport:{type(error).__name__[:64]}")


def live_page(origin: _Origin, page: _Page, deadline: float) -> dict[str, object]:
    evidence: dict[str, object] = {
        "route": page.route,
        "source": page.source,
        "expectedSha256": hashlib.sha256(page.body.encode()).hexdigest(),
    }
    remaining = deadline - time.monotonic()
    if remaining <= 0:
        return {**evidence, "outcome": "NOT_FETCHED", "reason": "DEADLINE"}
    remote = fetch(origin, page, min(15, remaining))
    if isinstance(remote, Rejected):
        return {
            **evidence,
            "outcome": "FETCH_FAILED",
            "failure": {"code": remote.code, "detail": remote.detail},
        }
    evidence["outcome"] = "MATCH" if content_matches(page, remote, origin) else "CONTENT_MISMATCH"
    evidence["responseSha256"] = hashlib.sha256(remote.encode()).hexdigest()
    return evidence


def live_receipt(
    origin: _Origin, results: list[dict[str, object]], outcome: str
) -> dict[str, object]:
    receipt: dict[str, object] = {"type": outcome, "origin": origin.value, "pages": results}
    checker_commit = os.environ.get("GITHUB_SHA", "")
    source_commit = os.environ.get("SLOPSENTRAL_SITE_EXPECTED_COMMIT", checker_commit)
    if re.fullmatch(r"[0-9a-f]{40}", source_commit):
        receipt["expectedCommit"] = source_commit
    if re.fullmatch(r"[0-9a-f]{40}", checker_commit):
        receipt["checkerCommit"] = checker_commit
    return receipt


def live(projection: _Projection, origin: _Origin, timeout: int) -> dict[str, object]:
    end = time.monotonic() + timeout
    results: list[dict[str, object]] = []
    while True:
        # Timeout zero requests one pass. Timed retries do not start network
        # effects after their deadline. Eight workers limit transport overrun.
        deadline = end if timeout else time.monotonic() + 15 * (len(projection.pages) // 8 + 1)
        with ThreadPoolExecutor(max_workers=8) as workers:
            futures = [
                workers.submit(live_page, origin, page, deadline) for page in projection.pages
            ]
            latest = [future.result() for future in futures]
        results = (
            [
                {
                    **previous,
                    "lastAttempt": {"outcome": "NOT_FETCHED", "reason": current["reason"]},
                }
                if current["outcome"] == "NOT_FETCHED"
                else current
                for previous, current in zip(results, latest, strict=True)
            ]
            if results
            else latest
        )
        # Retained responses aid diagnosis. Only one complete fresh pass grants LIVE.
        if all(result["outcome"] == "MATCH" for result in latest):
            return live_receipt(origin, results, "LIVE")
        if time.monotonic() >= end:
            return live_receipt(origin, results, "STALE")
        time.sleep(min(30, max(0, end - time.monotonic())))
        if time.monotonic() >= end:
            return live_receipt(origin, results, "STALE")


def live_command(
    projection: _Projection, base_url: str, timeout: int
) -> dict[str, object] | Rejected:
    origin = admit_origin(base_url)
    if isinstance(origin, Rejected):
        return origin
    if timeout < 0:
        return Rejected(Code.INPUT, "timeout must not be negative")
    return live(projection, origin, timeout)


def run_command(
    root: Path, command: Command, base_url: str, timeout: int
) -> dict[str, object] | Rejected:
    projection = prepare(root)
    if isinstance(projection, Rejected):
        return projection
    output = admit_output(root, projection)
    if isinstance(output, Rejected):
        return output
    match command:
        case Command.CHECK:
            stale = examine(root, projection)
            return {"type": "STALE" if stale else "CURRENT", "paths": stale}
        case Command.SYNC:
            failure = synchronize(output)
            return (
                failure
                if failure is not None
                else {"type": "SYNCED", "pages": len(projection.pages)}
            )
        case Command.LIVE:
            return live_command(projection, base_url, timeout)
    assert_never(command)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    _ = parser.add_argument("command", type=Command, choices=list(Command))
    _ = parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parents[1])
    _ = parser.add_argument("--base-url", default="https://slopsentral.michne.com")
    _ = parser.add_argument("--timeout", type=int, default=0)
    args = parser.parse_args()
    root: Path = args.repo
    command: Command = args.command
    origin: str = args.base_url
    timeout: int = args.timeout
    outcome = run_command(root.resolve(), command, origin, timeout)
    if isinstance(outcome, Rejected):
        print(json.dumps({"type": "REJECTED", "code": outcome.code, "detail": outcome.detail}))
        return 2
    print(json.dumps(outcome))
    return 1 if outcome["type"] == "STALE" else 0


if __name__ == "__main__":
    sys.exit(main())
